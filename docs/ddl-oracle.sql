CREATE TABLE dddj_cabazes (
    codigo          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo          VARCHAR2(120) NOT NULL,
    categoria       VARCHAR2(60)  NOT NULL,
    peso_kg         FLOAT(53)     NOT NULL,
    preco           FLOAT(53)     NOT NULL,
    quiosque        VARCHAR2(120) NOT NULL,
    feirante        VARCHAR2(120) NOT NULL,
    gratuito_ong    NUMBER(1)     NOT NULL,
    status          VARCHAR2(20)  NOT NULL,
    codigo_qr       VARCHAR2(36),
    data_publicacao DATE          NOT NULL,
    url_imagem      VARCHAR2(255),
    CONSTRAINT uk_cabaz_codigo_qr UNIQUE (codigo_qr),
    CONSTRAINT ck_cabaz_ong       CHECK (gratuito_ong IN (0, 1)),
    CONSTRAINT ck_cabaz_status    CHECK (status IN ('DISPONIVEL', 'RESERVADO', 'RETIRADO'))
);

